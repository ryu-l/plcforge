"""Independent expected-behaviour cases for the weaker paths of the pipeline.

The round-trip tests hold the translator to "consistent with itself": both
directions are produced by plcforge, so they can agree and still both be wrong.
The tests here hold it to expectations that were written down by hand from the
IEC 61131-3 semantics before any plcforge output existed.  If a translation
disagrees, it is the translation that is wrong, not the expectation.

Two weak spots named by the coverage baseline are the focus: the identifier
mapping (``backends/naming.py``) and the Python -> Structured Text lifting
direction (``frontends/python/lifter.py``).  The hand written Python sources in
this file are authored here, not generated by the tool, and their expected
outputs are computed by hand - the hand written module itself is never executed
to produce the numbers.
"""

from __future__ import annotations

import pytest

from conftest import build, load_generated
from plcforge.backends.naming import (
    class_name,
    cpp_name,
    module_name,
    python_name,
    sanitize,
    unique,
)
from plcforge.backends.python.emitter import emit_project as emit_python
from plcforge.backends.st.emitter import emit_project as emit_st
from plcforge.diagnostics import DiagnosticBag
from plcforge.frontends.python.lifter import lift_source
from plcforge.frontends.st.parser import parse_source
from plcforge.ir.link import link_types
from plcforge.ir.validate import resolve_types
from plcforge.runtime import SimulatedClock, use_clock


def lift_and_render(source: str, name: str) -> str:
    """Lift hand written Python to ST, then render that ST as runnable Python.

    Returns the *second* generation: the module that comes back from the
    Structured Text rendering.  This is the path a control engineer would take
    through the tool, and the one whose behaviour the expectations pin down.
    """
    diagnostics = DiagnosticBag()
    lifted = lift_source(source, f"{name}.py", diagnostics, project_name=name)
    link_types(lifted, diagnostics)
    resolve_types(lifted, diagnostics)
    assert not diagnostics.has_errors, diagnostics.summary()

    text = emit_st(lifted, None, diagnostics)
    assert not diagnostics.has_errors, diagnostics.summary()

    reparsed = parse_source(text, f"{name}.st", diagnostics, project_name=name)
    reparse_diagnostics = diagnostics
    link_types(reparsed, reparse_diagnostics)
    resolve_types(reparsed, reparse_diagnostics)
    assert not reparse_diagnostics.has_errors, reparse_diagnostics.summary()

    code = emit_python(reparsed, None, reparse_diagnostics)
    return code


class TestIdentifierMapping:
    """Expected spellings for the identifier mapping, decided by hand.

    These are the answers an engineer would predict from the documentation: a
    direct address becomes a readable name, a target language keyword gains an
    underscore, and everything else keeps the author's spelling.
    """

    @pytest.mark.parametrize(
        ("name", "expected"),
        [
            ("%IX0.0", "input_x0_0"),
            ("%QW2.3", "output_w2_3"),
            ("%MD5", "memory_d5"),
            ("%ix0.0", "input_x0_0"),
            ("Motor Start", "Motor_Start"),
            ("9volts", "_9volts"),
            ("already_fine", "already_fine"),
        ],
    )
    def test_plc_identifiers_get_predicted_target_spellings(self, name: str, expected: str) -> None:
        assert sanitize(name) == expected

    def test_python_keywords_gain_an_underscore_and_others_do_not(self) -> None:
        assert python_name("class") == "class_"
        assert python_name("lambda") == "lambda_"
        assert python_name("match") == "match_"
        assert python_name("case") == "case_"
        assert python_name("conveyor") == "conveyor"

    def test_cpp_keywords_gain_an_underscore_and_others_do_not(self) -> None:
        assert cpp_name("class") == "class_"
        assert cpp_name("namespace") == "namespace_"
        assert cpp_name("template") == "template_"
        assert cpp_name("plant") == "plant"

    def test_class_names_keep_the_authors_spelling(self) -> None:
        assert class_name("ConveyorSegment") == "ConveyorSegment"
        assert class_name("conveyor_segment") == "ConveyorSegment"
        assert class_name("FB_Motor") == "FB_Motor"
        assert class_name("motor") == "Motor"

    def test_module_names_are_snake_case(self) -> None:
        assert module_name("ConveyorSegment") == "conveyor_segment"
        assert module_name("FB_Motor") == "fb_motor"
        assert module_name("class") == "class_"

    def test_collisions_are_numbered_from_two_without_disturbing_new_names(self) -> None:
        taken: set[str] = set()
        assert unique("motor", taken) == "motor"
        assert unique("motor", taken) == "motor_2"
        assert unique("motor", taken) == "motor_3"
        assert unique("pump", taken) == "pump"

    def test_identifiers_hostile_to_both_targets_still_run(self, tmp_path) -> None:
        """'class', 'template' and 'namespace' in one POU, all readable targets."""
        module, _ = build_and_run(
            """
            FUNCTION_BLOCK Valve
            VAR_INPUT class : DINT; template : BOOL; END_VAR
            VAR_OUTPUT namespace : DINT; END_VAR
                IF template THEN
                    namespace := class;
                END_IF;
            END_FUNCTION_BLOCK
            """,
            tmp_path,
            "expected_keywords",
        )
        assert module.Valve()(class_=5, template=True).namespace == 5
        assert module.Valve()(class_=5, template=False).namespace == 0

    def test_named_variables_keep_names_and_addresses_are_metadata(self, tmp_path) -> None:
        module, _ = build_and_run(
            """
            FUNCTION_BLOCK Io
            VAR_INPUT start AT %IX0.0 : BOOL; END_VAR
            VAR_OUTPUT lamp AT %QW0.0 : BOOL; END_VAR
                lamp := start;
            END_FUNCTION_BLOCK
            """,
            tmp_path,
            "expected_addresses",
        )
        assert module.Io()(start=True).lamp is True


def build_and_run(source: str, tmp_path, name: str):
    project, diagnostics = build(source, tmp_path)
    code = emit_python(project, None, diagnostics)
    assert not diagnostics.has_errors, diagnostics.summary()
    return load_generated(code, name), code


class TestLiftedHandWrittenPython:
    """Hand written Python, lifted to ST, rendered back, checked by hand.

    Each expected value below was computed from the IEC semantics before the
    test ran.  None of them came from executing the hand written module.
    """

    TANK = '''
from enum import IntEnum

from plcforge.runtime import DINT, REAL, R_TRIG, TON, BOOL, FunctionBlock


class Level(IntEnum):
    Low = 0
    High = 1


class Tank(FunctionBlock):
    """Hand written block: fills while the inlet runs, drains on demand."""

    def __init__(self, clock=None):
        super().__init__(clock)
        # VAR_INPUT
        self.inlet: BOOL = False
        self.demand: BOOL = False
        # VAR_OUTPUT
        self.content: REAL = 0.0
        self.level: Level = Level.Low
        # VAR
        self.fill_timer: TON = TON(clock)
        self.drain_edge: R_TRIG = R_TRIG(clock)
        self.drains: DINT = 0

    def body(self):
        self.fill_timer(IN=self.inlet, PT=3.0)
        self.drain_edge(CLK=self.demand)
        if self.drain_edge.Q:
            self.drains = self.drains + 1
        if self.fill_timer.Q:
            self.level = Level.High
        elif self.demand:
            self.level = Level.Low
        self.content = (self.content + 1.0) if self.inlet else (self.content - 0.5)
'''

    def test_a_lifted_tank_matches_its_hand_computed_trace(self) -> None:
        code = lift_and_render(self.TANK, "tank")
        module = load_generated(code, "expected_tank")

        # Hand computed, one second per scan: the fill timer needs three whole
        # seconds of IN, the drain edge fires once, and the content moves by
        # +1.0 while the inlet is open and -0.5 otherwise.
        scenario = [
            (True, False),
            (True, False),
            (True, False),
            (True, False),
            (False, True),
            (False, False),
        ]
        expected = [
            (1.0, "Low", 0),
            (2.0, "Low", 0),
            (3.0, "Low", 0),
            (4.0, "High", 0),
            (3.5, "Low", 1),
            (3.0, "Low", 1),
        ]

        clock = SimulatedClock()
        with use_clock(clock):
            tank = module.Tank()
            trace = []
            for inlet, demand in scenario:
                tank(inlet=inlet, demand=demand)
                trace.append((tank.content, tank.level.name, tank.drains))
                clock.advance(1.0)

        assert trace == expected

    NUMERICS = '''
def quarter(value: DINT) -> DINT:
    """One quarter, truncating toward zero as the controller does."""
    return idiv(value, 4)


def rest(value: DINT) -> DINT:
    """Remainder following the sign of the dividend."""
    return imod(value, 4)


def clip(value: DINT) -> DINT:
    """Clamped into the working band, IEC argument order."""
    return LIMIT(10, value, 20)


def narrowed(value: REAL) -> DINT:
    """A REAL narrowed to DINT truncates, it does not round."""
    return convert(value, "DINT")
'''

    def test_lifted_numeric_helpers_match_hand_computed_values(self) -> None:
        code = lift_and_render(self.NUMERICS, "numerics")
        module = load_generated(code, "expected_numerics")

        # -9/4 truncates to -2 (floor would give -3); -9 MOD 4 is -1 (Python's
        # % would give 3); clipping is inclusive; 2.9 truncates to 2.
        assert module.quarter(-9) == -2
        assert module.quarter(9) == 2
        assert module.rest(-9) == -1
        assert module.rest(9) == 1
        assert module.clip(5) == 10
        assert module.clip(15) == 15
        assert module.clip(99) == 20

    @pytest.mark.xfail(
        strict=True,
        raises=NameError,
        reason="OFFLINE-001: convert(value, DINT) lifts to undefined TO_DINT; see offline-expanded.md",
    )
    def test_lifted_conversion_matches_independent_expectation(self) -> None:
        code = lift_and_render(
            'def narrowed(value: REAL) -> DINT:\n    return convert(value, "DINT")\n',
            "conversion_repro",
        )
        module = load_generated(code, "expected_conversion")
        assert module.narrowed(2.9) == 2
        assert module.narrowed(-2.9) == -2

    LOOPS = '''
def total_to(last: DINT) -> DINT:
    """Sum 1..last; the IEC bound is inclusive, Python's range is not."""
    total = 0
    for i in range(1, last + 1):
        total = total + i
    return total


def backwards(start: DINT, stop: DINT) -> DINT:
    """Sum start, start-2, ... down to and including stop."""
    total = 0
    for i in iec_range(start, stop, -2):
        total = total + i
    return total


def halving_steps(value: DINT) -> DINT:
    """How many halvings until the value is exhausted (REPEAT shape)."""
    steps = 0
    while True:
        value = idiv(value, 2)
        steps = steps + 1
        if value <= 0:
            break
    return steps
'''

    def test_lifted_loop_shapes_match_hand_computed_totals(self) -> None:
        code = lift_and_render(self.LOOPS, "loops")
        module = load_generated(code, "expected_loops")

        # 1+2+3+4 = 10 (an exclusive bound would give 6); 5+3+1 = 9;
        # 7 -> 3 -> 1 -> 0 is three truncating halvings.
        assert module.total_to(4) == 10
        assert module.total_to(1) == 1
        assert module.backwards(5, 1) == 9
        assert module.backwards(8, 2) == 8 + 6 + 4 + 2
        assert module.halving_steps(7) == 3
        assert module.halving_steps(8) == 4
        assert module.halving_steps(0) == 1, "REPEAT runs the body once before testing"

    TYPES = '''
from dataclasses import dataclass
from enum import IntEnum

from plcforge.runtime import REAL, FunctionBlock, Struct


class Mode(IntEnum):
    Manual = 0
    Auto = 1


@dataclass
class Limits(Struct):
    high: REAL = 80.0
    low: REAL = 20.0


class Band(FunctionBlock):
    """Hand written: reports the span and the working mode."""

    def __init__(self, clock=None):
        super().__init__(clock)
        # VAR
        self.limits: Limits = Limits(high=80.0, low=20.0)
        # VAR_OUTPUT
        self.span: REAL = 0.0
        self.mode: Mode = Mode.Manual

    def body(self):
        self.span = self.limits.high - self.limits.low
        self.mode = Mode.Auto
'''

    def test_lifted_enums_and_structs_match_hand_computed_values(self) -> None:
        code = lift_and_render(self.TYPES, "types")
        module = load_generated(code, "expected_types")

        block = module.Band()()
        assert block.span == pytest.approx(60.0)
        assert block.mode is module.Mode.Auto
        assert module.Limits(low=5.0).to_dict() == {"high": 80.0, "low": 5.0}


class TestRealMagnitudes:
    """REAL arithmetic checked against hand written magnitudes.

    REAL on a controller is 32 bit; the tolerances below are chosen so a
    correct 32 or 64 bit evaluation passes and a semantic error (a wrong
    operator, a lost conversion) does not.
    """

    def test_real_results_match_hand_computed_magnitudes(self, tmp_path) -> None:
        module, _ = build_and_run(
            """
            FUNCTION_BLOCK Reals
            VAR_OUTPUT
                third : REAL;
                ten_halves : REAL;
                root_two : REAL;
                rounded : DINT;
                truncated : DINT;
            END_VAR
            VAR one : REAL := 1.0; count : DINT; running : REAL := 0.0; END_VAR
                third := one / 3.0;
                FOR count := 1 TO 10 DO
                    running := running + 0.1;
                END_FOR;
                ten_halves := running;
                root_two := SQRT(2.0);
                rounded := ROUND(2.5);
                truncated := TRUNC(-2.5);
            END_FUNCTION_BLOCK
            """,
            tmp_path,
            "expected_reals",
        )
        block = module.Reals()()
        assert block.third == pytest.approx(0.3333333, rel=1e-6)
        assert block.ten_halves == pytest.approx(1.0, rel=1e-6)
        assert block.root_two == pytest.approx(1.41421356, rel=1e-6)
        assert block.rounded == 3, "IEC ROUND is half away from zero, not banker's"
        assert block.truncated == -2, "TRUNC drops the fraction toward zero"
