"""C++ backend.

Emits a header-only C++17 translation plus the runtime header it needs, so the
result compiles with nothing but a standard toolchain:

    g++ -std=c++17 -I generated main.cpp -o plant

Two differences from the Python backend are worth knowing about.  C++ integer
division already truncates toward zero and ``%`` already follows the sign of the
dividend, so both map straight onto the native operators.  And a function block
instance is a struct with public fields, so a call with named parameters becomes
field assignments followed by ``instance()`` - order independent, and readable
next to the original.
"""

